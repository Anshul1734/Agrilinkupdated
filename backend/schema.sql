-- ---------------------------------------------------------------------------
-- place_order: the ONLY way an order is created. One transaction, so stock can never go negative,
-- two buyers can't both take the last unit, and an order is never saved without its lines.
-- Prices come from the Product table, never the client. Shipping is charged once per farmer.
-- Each farmer gets a notification.
-- ---------------------------------------------------------------------------

drop function if exists public.place_order(text, text, numeric, text, text, jsonb);

create or replace function public.place_order(
    p_buyer_id text,
    p_buyer_name text,
    p_shipping_per_seller numeric,
    p_address text,
    p_phone text,
    p_items jsonb
) returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
    v_order_id bigint;
    v_total numeric := 0;
    v_line record;
    v_prod record;
    v_seller record;
    v_sellers int;
begin
    if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
        raise exception 'empty_order';
    end if;

    insert into "Order" ("buyerId", "buyerName", "totalAmount", "shippingAmount", "shippingAddress", "contactNumber", status, "paymentMethod")
    values (p_buyer_id, p_buyer_name, 0, 0, p_address, p_phone, 'Pending', 'COD')
    returning id into v_order_id;

    -- Lines are merged per product and processed in id order so concurrent orders lock rows in the
    -- same order (no deadlocks).
    for v_line in
        select (e ->> 'productId')::bigint as product_id, sum((e ->> 'quantity')::int)::int as qty
        from jsonb_array_elements(p_items) e
        group by 1
        order by 1
    loop
        update "Product"
           set "quantityAvailable" = "quantityAvailable" - v_line.qty,
               "inStock" = ("quantityAvailable" - v_line.qty) > 0
         where id = v_line.product_id
           and "quantityAvailable" >= v_line.qty
           and "sellerId" is not null
        returning * into v_prod;

        if not found then
            raise exception 'insufficient_stock:%', v_line.product_id;
        end if;

        if v_prod."sellerId" = p_buyer_id then
            raise exception 'own_product:%', v_line.product_id;
        end if;

        insert into "OrderItem" ("orderId", "productId", "productName", unit, "unitPrice", quantity, "sellerId", "sellerName", status)
        values (v_order_id, v_prod.id, v_prod.name, v_prod.unit, v_prod.price, v_line.qty, v_prod."sellerId", v_prod."sellerName", 'Pending');

        v_total := v_total + v_prod.price * v_line.qty;
    end loop;

    select count(distinct "sellerId") into v_sellers from "OrderItem" where "orderId" = v_order_id;
    v_total := v_total + p_shipping_per_seller * v_sellers;
    update "Order" set "totalAmount" = v_total, "shippingAmount" = p_shipping_per_seller * v_sellers where id = v_order_id;

    for v_seller in
        select "sellerId", count(*)::int as n from "OrderItem" where "orderId" = v_order_id group by "sellerId"
    loop
        insert into "Notification" ("userId", type, title, body, link)
        values (v_seller."sellerId", 'order_placed', 'New order #' || v_order_id,
                p_buyer_name || ' ordered ' || v_seller.n || (case when v_seller.n = 1 then ' item' else ' items' end) || ' from you.',
                '/order/' || v_order_id);
    end loop;

    return v_order_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- update_order_item_status: enforces who may move a line to which status, returns stock on cancel
-- (row-locked so two requests can't both restock) and notifies the other party.
--   seller: Pending -> Processing | Cancelled, Processing -> Shipped | Cancelled, Shipped -> Delivered
--   buyer : Pending -> Cancelled
-- ---------------------------------------------------------------------------

create or replace function public.update_order_item_status(
    p_item_id bigint,
    p_actor_id text,
    p_new_status text
) returns "OrderItem"
language plpgsql
security definer
set search_path = public
as $$
declare
    v_item "OrderItem";
    v_buyer text;
    v_is_seller boolean;
    v_is_buyer boolean;
    v_ok boolean := false;
begin
    select * into v_item from "OrderItem" where id = p_item_id for update;
    if not found then
        raise exception 'not_found';
    end if;

    select "buyerId" into v_buyer from "Order" where id = v_item."orderId";
    v_is_seller := v_item."sellerId" = p_actor_id;
    v_is_buyer := v_buyer = p_actor_id;

    if not (v_is_seller or v_is_buyer) then
        raise exception 'not_found';   -- don't reveal that the line exists
    end if;

    if v_is_seller then
        v_ok := (v_item.status, p_new_status) in
            (('Pending', 'Processing'), ('Pending', 'Cancelled'),
             ('Processing', 'Shipped'), ('Processing', 'Cancelled'),
             ('Shipped', 'Delivered'));
    end if;
    if not v_ok and v_is_buyer then
        v_ok := v_item.status = 'Pending' and p_new_status = 'Cancelled';
    end if;

    if not v_ok then
        raise exception 'invalid_transition:%->%', v_item.status, p_new_status;
    end if;

    if p_new_status = 'Cancelled' and v_item."productId" is not null then
        update "Product"
           set "quantityAvailable" = "quantityAvailable" + v_item.quantity,
               "inStock" = true
         where id = v_item."productId";
    end if;

    update "OrderItem" set status = p_new_status where id = p_item_id returning * into v_item;

    if v_is_seller and not v_is_buyer then
        insert into "Notification" ("userId", type, title, body, link)
        values (v_buyer, 'order_status', 'Order #' || v_item."orderId" || ' update',
                v_item."productName" || ' is now ' || lower(p_new_status) || '.', '/order/' || v_item."orderId");
    elsif v_is_buyer and not v_is_seller then
        insert into "Notification" ("userId", type, title, body, link)
        values (v_item."sellerId", 'order_status', 'Order #' || v_item."orderId" || ' update',
                'The buyer cancelled ' || v_item."productName" || '.', '/order/' || v_item."orderId");
    end if;

    return v_item;
end;
$$;

-- ---------------------------------------------------------------------------
-- Reviews. submit_review only accepts a review from the buyer of a Delivered line, once per line,
-- and keeps Product.rating / Product.reviews in sync inside the same transaction.
-- ---------------------------------------------------------------------------

create or replace function public.refresh_product_rating(p_product_id bigint) returns void
language sql
security definer
set search_path = public
as $$
    update "Product" p
       set rating = coalesce((select round(avg(rating)::numeric, 2) from "Review" where "productId" = p_product_id), 0),
           reviews = (select count(*) from "Review" where "productId" = p_product_id)
     where p.id = p_product_id;
$$;

create or replace function public.submit_review(
    p_item_id bigint,
    p_buyer_id text,
    p_buyer_name text,
    p_rating int,
    p_comment text
) returns "Review"
language plpgsql
security definer
set search_path = public
as $$
declare
    v_item "OrderItem";
    v_buyer text;
    v_review "Review";
    v_seller_name text;
begin
    if p_rating is null or p_rating < 1 or p_rating > 5 then
        raise exception 'invalid_rating';
    end if;

    select * into v_item from "OrderItem" where id = p_item_id;
    if not found then
        raise exception 'not_found';
    end if;
    select "buyerId" into v_buyer from "Order" where id = v_item."orderId";
    if v_buyer is distinct from p_buyer_id then
        raise exception 'not_found';
    end if;
    if v_item.status <> 'Delivered' then
        raise exception 'not_delivered';
    end if;
    if v_item."productId" is null then
        raise exception 'product_gone';
    end if;
    if exists (select 1 from "Review" where "orderItemId" = p_item_id) then
        raise exception 'already_reviewed';
    end if;

    -- Serialise reviewers of the same product. Without this lock, two simultaneous reviews would each compute the
    -- average without seeing the other's uncommitted row and leave Product.rating / reviews permanently stale.
    perform 1 from "Product" where id = v_item."productId" for update;

    insert into "Review" ("productId", "orderItemId", "reviewerId", "reviewerName", rating, comment)
    values (v_item."productId", p_item_id, p_buyer_id, p_buyer_name, p_rating, coalesce(btrim(p_comment), ''))
    returning * into v_review;

    perform refresh_product_rating(v_item."productId");

    insert into "Notification" ("userId", type, title, body, link)
    values (v_item."sellerId", 'review', 'New ' || p_rating || '-star review',
            p_buyer_name || ' reviewed ' || v_item."productName" || '.', '/product/' || v_item."productId");

    return v_review;
end;
$$;

create or replace function public.delete_review(p_review_id bigint, p_buyer_id text) returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_product bigint;
begin
    select "productId" into v_product from "Review" where id = p_review_id and "reviewerId" = p_buyer_id;
    if not found then
        raise exception 'not_found';
    end if;
    -- Same product-level lock as submit_review so the recomputed aggregate always includes every committed review.
    perform 1 from "Product" where id = v_product for update;
    delete from "Review" where id = p_review_id and "reviewerId" = p_buyer_id;
    if not found then
        raise exception 'not_found';   -- deleted by a concurrent request in the meantime
    end if;
    perform refresh_product_rating(v_product);
end;
$$;

