-- In-stock product count per category (used on the home and category pages).
create or replace function public.category_counts()
returns table ("categoryId" int, n int)
language sql
stable
security definer
set search_path = public
as $$
    select "categoryId", count(*)::int from "Product" where "quantityAvailable" > 0 and "categoryId" is not null group by "categoryId";
$$;

-- Delivered, not-yet-reviewed lines of one product that this buyer received (what they may review now).
create or replace function public.eligible_review_items(p_buyer_id text, p_product_id bigint)
returns table ("orderItemId" bigint, "orderId" bigint)
language sql
stable
security definer
set search_path = public
as $$
    select i.id, i."orderId"
      from "OrderItem" i
      join "Order" o on o.id = i."orderId"
     where o."buyerId" = p_buyer_id
       and i."productId" = p_product_id
       and i.status = 'Delivered'
       and not exists (select 1 from "Review" r where r."orderItemId" = i.id)
     order by i.id;
$$;

-- Dashboard numbers over ALL of a user's orders (not just the first page).
--   Farmer: orders, openItems (Pending/Processing/Shipped lines), revenue (Delivered lines), months (last 6, UTC, non-cancelled)
--   Buyer : orders, inProgress (any live line still open), delivered (all live lines delivered), spent (live lines + shipping)
create or replace function public.order_stats(p_user_id text, p_role text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
    v jsonb;
begin
    if p_role = 'Farmer' then
        select jsonb_build_object(
                   'orders', count(distinct "orderId"),
                   'openItems', count(*) filter (where status in ('Pending', 'Processing', 'Shipped')),
                   'revenue', coalesce(sum("unitPrice" * quantity) filter (where status = 'Delivered'), 0))
          into v
          from "OrderItem" where "sellerId" = p_user_id;

        v := v || jsonb_build_object('months', coalesce((
            select jsonb_agg(jsonb_build_object('month', m, 'sales', s) order by m)
              from (select to_char(date_trunc('month', created_at at time zone 'utc'), 'YYYY-MM') as m,
                           sum("unitPrice" * quantity) as s
                      from "OrderItem"
                     where "sellerId" = p_user_id
                       and status <> 'Cancelled'
                       and (created_at at time zone 'utc') >= date_trunc('month', now() at time zone 'utc') - interval '5 months'
                     group by 1) t), '[]'::jsonb));
    else
        select jsonb_build_object(
                   'orders', count(*),
                   'inProgress', count(*) filter (where open_n > 0),
                   'delivered', count(*) filter (where live_n > 0 and open_n = 0),
                   'spent', coalesce(sum(case when live_n > 0 then live_sum + shipping else 0 end), 0))
          into v
          from (select o.id,
                       o."shippingAmount" as shipping,
                       count(*) filter (where i.status <> 'Cancelled') as live_n,
                       count(*) filter (where i.status in ('Pending', 'Processing', 'Shipped')) as open_n,
                       coalesce(sum(i."unitPrice" * i.quantity) filter (where i.status <> 'Cancelled'), 0) as live_sum
                  from "Order" o
                  join "OrderItem" i on i."orderId" = o.id
                 where o."buyerId" = p_user_id
                 group by o.id) t;
    end if;
    return v;
end;
$$;

