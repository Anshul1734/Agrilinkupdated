create table if not exists public."Order" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "buyerId" TEXT,
    "buyerName" TEXT,
    "totalAmount" NUMERIC NOT NULL,
    status TEXT DEFAULT 'Pending',  -- legacy; the effective status is derived from OrderItem.status
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- One row per product line. Status lives here because one order can span several farmers,
-- and each farmer fulfils (and may cancel) only their own lines.
create table if not exists public."OrderItem" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "orderId" BIGINT NOT NULL REFERENCES public."Order"(id) ON DELETE CASCADE,
    "productId" BIGINT REFERENCES public."Product"(id) ON DELETE SET NULL,
    "productName" TEXT NOT NULL,       -- snapshots, so history survives product edits/deletes
    unit TEXT,
    "unitPrice" NUMERIC NOT NULL CHECK ("unitPrice" >= 0),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    "sellerId" TEXT NOT NULL,
    "sellerName" TEXT,
    status TEXT NOT NULL DEFAULT 'Pending',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Messages from the public contact form. Read them in the Supabase dashboard (Table editor).
