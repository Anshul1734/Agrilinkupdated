-- Agrilink database schema.
--
-- Run this whole file in the Supabase SQL Editor. It is idempotent: it works on a
-- fresh project AND upgrades the original v1 schema in place (existing rows are kept).
--
-- Security model: every table has Row Level Security enabled with NO policies, so the
-- public anon key (which ships in browsers) can read/write nothing. Only the Express
-- backend, using the service_role key, touches the database - after verifying the
-- caller's Firebase ID token and checking ownership.

