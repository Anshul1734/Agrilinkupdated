    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    "categoryId" INTEGER REFERENCES public."Category"(id),
    "categoryName" TEXT,
    price NUMERIC NOT NULL,
    "quantityAvailable" INTEGER NOT NULL,
    "sellerId" TEXT,
    "sellerName" TEXT,
    "productionType" TEXT,
    "imageUrl" TEXT,
    "farmerId" TEXT,       -- legacy duplicate of sellerId, no longer written
    "farmerName" TEXT,     -- legacy duplicate of sellerName, no longer written
    category TEXT,         -- legacy duplicate of categoryName, no longer written
    rating NUMERIC DEFAULT 0,
    reviews INTEGER DEFAULT 0,
    "inStock" BOOLEAN DEFAULT true,
    unit TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
